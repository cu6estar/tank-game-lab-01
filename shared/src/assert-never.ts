/**
 * Заглушка для `default:` у switch по дискримінованому об'єднанню. Якщо в
 * union з'явиться новий варіант без `case`, у цю функцію потрапить не `never`,
 * а цей варіант — і tsc скаже, що він "не присвоюється типу never".
 * У рантаймі сюди дійти не повинно (дані з мережі перевіряє Zod/декодер),
 * тому кидаємо помилку, а не мовчимо.
 */
export function assertNever(value: never, what = 'значення'): never {
  throw new Error(`Необроблений варіант (${what}): ${JSON.stringify(value)}`);
}
